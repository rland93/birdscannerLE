//! of Command Complete follow sdk-nrf `hci_internal.c`
//! (`command_generates_command_complete_event`).
//!
//! Left out because the nRF53 library does not contain them: Channel Sounding
//! (`le_cs_*`, `vs_cs_params_set`), Read Local Supported Commands (v1/v2) and
//! LE Read Supported States (sdk-nrf synthesises those in C). They answer
//! "Unknown HCI Command". Regenerate when bumping nrf-sdc-sys; missing
//! symbols show up as link errors.

